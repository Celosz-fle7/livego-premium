  _AesCore(Uint8List key) {
    _keyExpansion(key);
  }

  void _keyExpansion(Uint8List key) {
    _rk = List<int>.filled(44, 0);
    for (int i = 0; i < 4; i++) {
      _rk[i] = (key[4 * i] << 24) | (key[4 * i + 1] << 16) | (key[4 * i + 2] << 8) | key[4 * i + 3];
    }
    for (int i = 4; i < 44; i++) {
      int temp = _rk[i - 1];
      if (i % 4 == 0) {
        temp = ((temp << 8) | ((temp >> 24) & 0xff)) & 0xffffffff;
        temp = (_sBox[(temp >> 24) & 0xff] << 24) |
            (_sBox[(temp >> 16) & 0xff] << 16) |
            (_sBox[(temp >> 8) & 0xff] << 8) |
            _sBox[temp & 0xff];
        temp ^= (_rCon[i ~/ 4] << 24);
      }
      _rk[i] = (_rk[i - 4] ^ temp) & 0xffffffff;
    }
  }

  Uint8List decryptBlock(Uint8List input) {
    final state = List<int>.generate(16, (i) => input[i]);

    _addRoundKey(state, 10);
    for (int round = 9; round >= 1; round--) {
      _invShiftRows(state);
      _invSubBytes(state);
      _addRoundKey(state, round);
      _invMixColumns(state);
    }
    _invShiftRows(state);
    _invSubBytes(state);
    _addRoundKey(state, 0);

    return Uint8List.fromList(state);
  }

  void _addRoundKey(List<int> state, int round) {
    for (int i = 0; i < 4; i++) {
      final w = _rk[round * 4 + i];
      state[4 * i] ^= (w >> 24) & 0xff;
      state[4 * i + 1] ^= (w >> 16) & 0xff;
      state[4 * i + 2] ^= (w >> 8) & 0xff;
      state[4 * i + 3] ^= w & 0xff;
    }
  }

  void _invSubBytes(List<int> state) {
    for (int i = 0; i < 16; i++) {
      state[i] = _invSBox[state[i]];
    }
  }

  void _invShiftRows(List<int> state) {
    // Row 1
    int temp = state[13];
    state[13] = state[9];
    state[9] = state[5];
    state[5] = state[1];
    state[1] = temp;
    // Row 2
    temp = state[2];
    state[2] = state[10];
    state[10] = temp;
    temp = state[6];
    state[6] = state[14];
    state[14] = temp;
    // Row 3
    temp = state[3];
    state[3] = state[7];
    state[7] = state[11];
    state[11] = state[15];
    state[15] = temp;
  }

  int _gMul(int a, int b) {
    int p = 0;
    for (int i = 0; i < 8; i++) {
      if ((b & 1) != 0) p ^= a;
      final hi = a & 0x80;
      a = (a << 1) & 0xff;
      if (hi != 0) a ^= 0x1b;
      b >>= 1;
    }
    return p;
  }

  void _invMixColumns(List<int> state) {
    for (int c = 0; c < 4; c++) {
      final i = 4 * c;
      final s0 = state[i];
      final s1 = state[i + 1];
      final s2 = state[i + 2];
      final s3 = state[i + 3];

      state[i] = _gMul(s0, 0x0e) ^ _gMul(s1, 0x0b) ^ _gMul(s2, 0x0d) ^ _gMul(s3, 0x09);
      state[i + 1] = _gMul(s0, 0x09) ^ _gMul(s1, 0x0e) ^ _gMul(s2, 0x0b) ^ _gMul(s3, 0x0d);
      state[i + 2] = _gMul(s0, 0x0d) ^ _gMul(s1, 0x09) ^ _gMul(s2, 0x0e) ^ _gMul(s3, 0x0b);
      state[i + 3] = _gMul(s0, 0x0b) ^ _gMul(s1, 0x0d) ^ _gMul(s2, 0x09) ^ _gMul(s3, 0x0e);
    }
  }
