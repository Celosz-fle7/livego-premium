/// Utilitas Kriptografi ShortTV (RC4 & AES-128-CBC) untuk LiveGo Mandiri.
class ShortTvCrypto {
  /// Kunci default RC4 yang didapat dari APK ShortTV
  static const String defaultRc4Key = 'wEG31caHzIq6lPs7uXg2xnsBoW384ECT';

  /// IV tetap untuk segmen MPEG-TS ShortTV
  static const String tsAesIv = 'shortmax00000000';

  /// RC4 KSA & PRGA stream cipher
  static Uint8List rc4Crypt(Uint8List data, String key) {
    final keyBytes = latin1.encode(key);
    final s = List<int>.generate(256, (i) => i);
    int j = 0;
    for (int i = 0; i < 256; i++) {
      j = (j + s[i] + keyBytes[i % keyBytes.length]) & 255;
      final temp = s[i];
      s[i] = s[j];
      s[j] = temp;
    }

    int i = 0;
    j = 0;
    final out = Uint8List(data.length);
    for (int k = 0; k < data.length; k++) {
      i = (i + 1) & 255;
      j = (j + s[i]) & 255;
      final temp = s[i];
      s[i] = s[j];
      s[j] = temp;
      out[k] = data[k] ^ s[(s[i] + s[j]) & 255];
    }
    return out;
  }

  /// Enkripsi string menjadi hex string menggunakan RC4
  static String rc4EncryptHex(String plainText, String key) {
    final bytes = utf8.encode(plainText);
    final encrypted = rc4Crypt(Uint8List.fromList(bytes), key);
    final buffer = StringBuffer();
    for (final b in encrypted) {
      buffer.write(b.toRadixString(16).padLeft(2, '0'));
    }
    return buffer.toString();
  }

  /// Dekripsi hex string kembali ke plain text string menggunakan RC4
  static String rc4DecryptHex(String hexText, String key) {
    if (hexText.isEmpty) return '';
    final len = hexText.length ~/ 2;
    final bytes = Uint8List(len);
    for (int i = 0; i < len; i++) {
      bytes[i] = int.parse(hexText.substring(i * 2, i * 2 + 2), radix: 16);
    }
    final decrypted = rc4Crypt(bytes, key);
    return utf8.decode(decrypted, allowMalformed: true);
  }

  /// Hitung vefCode unik berdasarkan device ID
  static String calculateVefCode(String deviceId) {
    int sum = 0;
    for (int i = 0; i < deviceId.length; i++) {
      sum += deviceId.codeUnitAt(i);
    }
    final v1 = (sum % 7).toRadixString(16).toUpperCase();
    final v2 = (sum % 11).toRadixString(16).toUpperCase();
    final v3 = (sum % 13).toRadixString(16).toUpperCase();
    return '$v1$v2$v3';
  }

  /// Dekripsi segmen TS ShortTV (Header 1024 bytes -> AES-128-CBC)
  static Uint8List decryptTsSegment(Uint8List rawTs) {
    // Jika ukuran kurang dari 1024 byte, return apa adanya
    if (rawTs.length <= 1024) return rawTs;

    // Cek apakah sudah merupakan MPEG-TS standar (Sync byte 0x47 di offset 0)
    if (rawTs[0] == 0x47) return rawTs;

    // Parse header 1024 bytes
    try {
      final headerStr = utf8.decode(rawTs.sublist(0, 1024), allowMalformed: true);
      if (!headerStr.startsWith('shortmax')) {
        return rawTs;
      }

      final keyOffset = int.parse(headerStr.substring(16, 20));
      final encLen = int.parse(headerStr.substring(20, 24));
      final keyStr = headerStr.substring(keyOffset, keyOffset + 16);
      final keyBytes = utf8.encode(keyStr);
      final ivBytes = utf8.encode(tsAesIv);

      if (rawTs.length < 1024 + encLen) return rawTs;

      final encPart = rawTs.sublist(1024, 1024 + encLen);
      final decPart = _aesCbcDecrypt(encPart, Uint8List.fromList(keyBytes), Uint8List.fromList(ivBytes));

      // PKCS7 unpadding
      if (decPart.isEmpty) return rawTs;
      final padLen = decPart.last;
      final unpaddedLen = (padLen > 0 && padLen <= 16) ? decPart.length - padLen : decPart.length;
      final cleanHead = decPart.sublist(0, unpaddedLen.clamp(0, decPart.length));

      final restPart = rawTs.sublist(1024 + encLen);

      final fullTs = Uint8List(cleanHead.length + restPart.length);
      fullTs.setRange(0, cleanHead.length, cleanHead);
      fullTs.setRange(cleanHead.length, fullTs.length, restPart);
      return fullTs;
    } catch (_) {
      return rawTs;
    }
  }

  /// Implementasi AES-128-CBC Decryption murni tanpa dependensi eksternal berat
  static Uint8List _aesCbcDecrypt(Uint8List cipherText, Uint8List key, Uint8List iv) {
    final cipher = _AesCore(key);
    final plainText = Uint8List(cipherText.length);
    var prevBlock = iv;

    for (int i = 0; i < cipherText.length; i += 16) {
      if (i + 16 > cipherText.length) break;
      final block = cipherText.sublist(i, i + 16);
      final decryptedBlock = cipher.decryptBlock(block);
      for (int b = 0; b < 16; b++) {
        plainText[i + b] = decryptedBlock[b] ^ prevBlock[b];
      }
      prevBlock = block;
    }
    return plainText;
  }
}

